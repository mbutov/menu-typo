#!/usr/bin/env python3
"""Regenerates the diacritic folding table in src/typo.h.

A letter whose canonical decomposition (NFD) is one base letter plus
combining marks maps to that base letter: e-diaeresis to e, e-acute to e,
alpha-tonos to alpha. Covered: Latin (U+00C0-024F, U+1E00-1EFF), Greek
(U+0370-03FF, U+1F00-1FFF), Cyrillic (U+0400-052F).

Usage: tools/gen-fold.py   (rewrites the block between the GENERATED markers)
"""
import pathlib
import unicodedata

RANGES = [(0x00C0, 0x024F), (0x0370, 0x03FF), (0x0400, 0x052F),
          (0x1E00, 0x1EFF), (0x1F00, 0x1FFF)]
HEADER = pathlib.Path(__file__).resolve().parent.parent / "src" / "typo.h"
BEGIN = "/* BEGIN GENERATED by tools/gen-fold.py"
END = "/* END GENERATED */"


def table():
    pairs = []
    for first, last in RANGES:
        for cp in range(first, last + 1):
            ch = chr(cp)
            if not unicodedata.category(ch).startswith("L"):
                continue
            base = "".join(c for c in unicodedata.normalize("NFD", ch)
                           if unicodedata.category(c) != "Mn")
            if len(base) == 1 and base != ch:
                pairs.append((cp, ord(base)))
    return pairs


def main():
    pairs = table()
    rows = []
    for i in range(0, len(pairs), 4):
        rows.append("\t" + " ".join("{0x%04x, 0x%04x}," % p for p in pairs[i:i + 4]))
    block = "\n".join([
        BEGIN + ", Unicode %s, do not edit */" % unicodedata.unidata_version,
        "static const uint16_t typo_fold_table[][2] = {",
        *rows,
        "};",
        END,
    ])
    text = HEADER.read_text()
    start, end = text.index(BEGIN), text.index(END) + len(END)
    HEADER.write_text(text[:start] + block + text[end:])
    print("%s: %d letters" % (HEADER.name, len(pairs)))


if __name__ == "__main__":
    main()
